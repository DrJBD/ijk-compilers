"""
The feeder: turns any mix of .i, .j, .k and .ijk files into one
self-contained K program that loads them all into oK as a corpus.

    python3 feed.py FILE_OR_DIR [...] [-o feed.k] [-e EXPR]

What the program defines:

    docs    a list of the documents' own .k dicts, unchanged
    corpus  the same documents as columns: `name`title`body`text,
            each a list of strings, one entry per document

so `corpus`title lists every title and `{#x}'corpus`text gives every
length. Nothing else is defined. Which operations belong on top of
this is still open; see OPERATIONS.i.

Where each document's dict comes from:

    .k     used as it is
    .ijk   its k section; if it has none, its j section is compiled
    .i/.j  compiled through the pipeline, which must pass every stage

The output runs as `node repl.js feed.k`, can be piped into the
interactive REPL, and can be pasted into oK's browser REPL, which has
no file access. Each statement sits on one line because the REPL
reads a line at a time.

-e EXPR runs the feed plus EXPR through the real oK and prints the
result. --prelude FILE appends K definitions after the feed, such as
the candidate operations in candidate_ops.k.
"""

import argparse
import sys
import tempfile
from pathlib import Path

import ijk_files
import pipeline

_k_string = pipeline._stage2.k_string


def _compile(path: Path) -> str:
    result = pipeline.run_pipeline(path)
    if not result.ok:
        raise ValueError(result.summary())
    return result.k_source


def k_dict_for(path: Path) -> str:
    """The one-line K dict expression for a file of any ijk type."""
    if path.suffix == ".k":
        return path.read_text(encoding="utf-8").strip()
    if path.suffix == ".ijk":
        sections = ijk_files.unpack_ijk(path.read_bytes())
        if "k" in sections:
            return sections["k"][1].decode("utf-8").strip()
        source = sections.get("j") or sections["i"]
        with tempfile.TemporaryDirectory() as d:
            tmp = Path(d) / source[0]
            tmp.write_bytes(source[1])
            return _compile(tmp).strip()
    if path.suffix in (".i", ".j"):
        return _compile(path).strip()
    raise ValueError(f"{path.name}: not an ijk file")


def collect(targets) -> list:
    """Files in the order given; a directory contributes one file per
    name, preferring .k, then .ijk, then .j, then .i."""
    preference = (".k", ".ijk", ".j", ".i")
    files = []
    for t in targets:
        p = Path(t).expanduser()
        if not p.is_dir():
            files.append(p)
            continue
        best = {}
        for f in p.iterdir():
            if f.suffix in preference:
                current = best.get(f.stem)
                if current is None or preference.index(f.suffix) < preference.index(current.suffix):
                    best[f.stem] = f
        files.extend(best[name] for name in sorted(best))
    return files


def build_feed(files) -> str:
    lines = [
        "/ ijk feed -- generated by feed.py; " + f"{len(files)} document(s)",
        "/ docs: each document's .k dict. corpus: the same, as columns.",
        "docs:()",
    ]
    names = []
    for f in files:
        lines.append(f"docs,:,{k_dict_for(f)}")
        names.append(_k_string(f.stem))
    if len(names) == 1:
        name_list = "," + names[0]
    else:
        name_list = "(" + ";".join(names) + ")"
    lines.append(
        f"corpus:`name`title`body`text!({name_list};"
        "{x`title}'docs;{x`body}'docs;{x`text}'docs)"
    )
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Feed ijk files into oK as one corpus.")
    parser.add_argument("targets", nargs="+")
    parser.add_argument("-o", help="write the feed here instead of stdout")
    parser.add_argument("-e", dest="expr", help="run the feed plus this K expression in oK")
    parser.add_argument("--prelude", action="append", default=[],
                        help="K file to append after the feed (repeatable), e.g. candidate_ops.k")
    args = parser.parse_args(argv)

    files = collect(args.targets)
    if not files:
        print("no ijk files found", file=sys.stderr)
        return 1
    try:
        feed = build_feed(files)
    except ValueError as e:
        print(e, file=sys.stderr)
        return 1
    for prelude in args.prelude:
        feed += Path(prelude).read_text(encoding="utf-8").rstrip("\n") + "\n"

    if args.o:
        Path(args.o).write_text(feed, encoding="utf-8")
    if args.expr:
        result = pipeline._ok.run_k_file(feed + args.expr)
        print(result.stdout.rstrip("\n") if result.ok else "\n".join(result.errors))
        return 0 if result.ok else 1
    if not args.o:
        sys.stdout.write(feed)
    return 0


if __name__ == "__main__":
    sys.exit(main())
